import mongoose from "mongoose";

const userSchema = new mongoose.Schema({
  auth0Id: {
    type: String,
    required: true,
  },
  email: {
    type: String,
    required: true,
  },
  name: {
    type: String,
  },
  dob: {
    type: Date,
  },
  phoneNumber: {
    type: String,
    // You can add a match validator for phone number format if needed
    match: /^[\+]?[(]?[0-9]{3}[)]?[-\s\.]?[0-9]{3}[-\s\.]?[0-9]{4,6}$/,
  },
  addressLine1: {
    type: String,
  },
  city: {
    type: String,
  },
  country: {
    type: String,
  },
  role: {
    type: String,
    enum: ["ADMIN", "USER", "DELIVERY"],
  },
});

const User = mongoose.model("User", userSchema);
export default User;
